"""
gate_profiler.py - Adaptive Fast vs Heavy gate profiler (design R2-Q4, 6-minute threshold).

1. Detect the project's stack(s) from marker files and propose a fast (static + changed tests)
   command and a full-suite command.
2. Optionally time the full command (``--measure``), killing it at the threshold.
3. Decide the mode:
   - ``fast``  — full suite <= threshold: the agent runs it inline before story close and records
     the numbers in QUALITY.md itself.
   - ``heavy`` — full suite > threshold: the agent runs only the fast gates; the full suite becomes
     an out-of-band Heavy Gate script the user (or the Cockpit's QA & Heavy Gates tab) runs.
   A project that already ships ``scripts/gates.ps1`` + ``scripts/finalgates.ps1`` (money-nest) is
   recognised as ``heavy`` with those scripts, without re-measuring.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

import projects

DEFAULT_THRESHOLD_SECONDS = 360

HEAVY_SCRIPT_TEMPLATE = """#Requires -Version 5.1
# Heavy Gate for {name} — generated by PM & QA Board `profile-gates`.
# The full suite measured {measured} against a {threshold}s budget, so it runs out of band.
# Results land in {results_dir} for the Board's QA & Heavy Gates tab.
param([string]$Sprint = "", [string]$Sha = "")
$ErrorActionPreference = "Continue"
$runId = (Get-Date -Format "yyyyMMdd-HHmmss") + $(if ($Sprint) {{ "-story-$($Sprint -replace '\\.', '_')" }} else {{ "" }})
$runDir = Join-Path "{results_dir}" "runs\\$runId"
New-Item -ItemType Directory -Force -Path $runDir | Out-Null
Push-Location "{code_path}"
$start = Get-Date
& cmd /c "{full_cmd}" 2>&1 | Tee-Object -FilePath (Join-Path $runDir "full.log")
$code = $LASTEXITCODE
Pop-Location
$secs = [int]((Get-Date) - $start).TotalSeconds
$result = @{{ story = $Sprint; sha = $Sha; exit_code = $code; seconds = $secs; command = "{full_cmd}" }}
$result | ConvertTo-Json | Set-Content (Join-Path $runDir "results.json") -Encoding UTF8
"# Heavy Gate $runId`n`nExit code: $code in ${{secs}}s`n" | Set-Content (Join-Path $runDir "SUMMARY.md") -Encoding UTF8
exit $code
"""


def _has_script(pkg: Path, name: str) -> bool:
    try:
        return name in json.loads(pkg.read_text(encoding="utf-8")).get("scripts", {})
    except (OSError, json.JSONDecodeError):
        return False


def detect_stack(code_path: Path) -> dict[str, Any]:
    """Marker-file detection. Returns stacks + proposed fast/full commands (best effort)."""
    stacks: list[str] = []
    fast: list[str] = []
    full: list[str] = []

    if (code_path / "scripts" / "gates.ps1").exists() and (code_path / "scripts" / "finalgates.ps1").exists():
        return {
            "stacks": ["custom-gates"],
            "fast_cmd": "powershell -File scripts/gates.ps1",
            "full_cmd": "powershell -File scripts/finalgates.ps1",
            "declared_heavy": True,
        }

    py_roots = [p.parent for p in [code_path / "pyproject.toml", *code_path.glob("*/pyproject.toml")] if p.exists()]
    for root in py_roots:
        rel = "." if root == code_path else root.name
        stacks.append(f"python ({rel})")
        runner = "uv run" if shutil.which("uv") else "python -m"
        fast.append(f"{runner} ruff check {rel}")
        full.append(f"{runner} pytest -q {rel}".rstrip())

    for pkg in [code_path / "package.json", *code_path.glob("*/package.json")]:
        if not pkg.exists() or "node_modules" in pkg.parts:
            continue
        rel = "." if pkg.parent == code_path else pkg.parent.name
        pm = "pnpm" if (pkg.parent / "pnpm-lock.yaml").exists() or (code_path / "pnpm-lock.yaml").exists() else "npm"
        stacks.append(f"node ({rel})")
        prefix = f"{pm} --dir {rel}" if rel != "." else pm
        if _has_script(pkg, "lint"):
            fast.append(f"{prefix} run lint")
        if _has_script(pkg, "typecheck"):
            fast.append(f"{prefix} run typecheck")
        if _has_script(pkg, "test"):
            full.append(f"{prefix} test")

    if (code_path / "go.mod").exists():
        stacks.append("go")
        fast.append("go vet ./...")
        full.append("go test ./...")
    if (code_path / "Cargo.toml").exists():
        stacks.append("rust")
        fast.append("cargo clippy --quiet")
        full.append("cargo test --quiet")
    if any(code_path.glob("*.sln")) or any(code_path.glob("*.csproj")):
        stacks.append(".net")
        fast.append("dotnet build --nologo -v q")
        full.append("dotnet test --nologo")

    return {
        "stacks": stacks or ["unknown"],
        "fast_cmd": " && ".join(fast) or None,
        "full_cmd": " && ".join(full) or None,
        "declared_heavy": False,
    }


def measure(cmd: str, cwd: Path, threshold: int) -> dict[str, Any]:
    """Time ``cmd``; stop it once it passes the threshold (we only need to know it is over)."""
    start = time.monotonic()
    try:
        proc = subprocess.run(cmd, shell=True, cwd=str(cwd), capture_output=True, timeout=threshold + 5)
        return {"seconds": round(time.monotonic() - start, 1), "exit_code": proc.returncode, "timed_out": False}
    except subprocess.TimeoutExpired:
        return {"seconds": round(time.monotonic() - start, 1), "exit_code": None, "timed_out": True}


def decide(detected: dict[str, Any], measured: dict[str, Any] | None, threshold: int) -> dict[str, Any]:
    if detected.get("declared_heavy"):
        mode, reason = "heavy", "project already declares a fast/heavy gate split (gates.ps1 + finalgates.ps1)"
    elif measured is None:
        mode, reason = "unprofiled", "full suite not measured yet (re-run with --measure)"
    elif measured["timed_out"] or measured["seconds"] > threshold:
        mode, reason = "heavy", f"full suite took >{threshold}s — split into Fast + out-of-band Heavy gates"
    else:
        mode, reason = "fast", f"full suite took {measured['seconds']}s (<= {threshold}s) — run inline before close"
    return {
        "mode": mode,
        "reason": reason,
        "threshold_seconds": threshold,
        "fast": detected.get("fast_cmd"),
        "full": detected.get("full_cmd"),
        "measured_seconds": measured["seconds"] if measured else None,
        "stacks": detected.get("stacks"),
    }


def heavy_script_path(project: dict[str, Any]) -> Path:
    """Where a generated Heavy Gate script lives: never in the code repo for external docs."""
    if project.get("docs_mode") == "external":
        return Path(project["docs_path"]) / "gates" / "finalgates.ps1"
    return Path(project["code_path"]) / "scripts" / "finalgates.ps1"


def write_heavy_script(project: dict[str, Any], gates: dict[str, Any]) -> Path | None:
    target = heavy_script_path(project)
    if target.exists() or not gates.get("full"):
        return None
    results_dir = (
        Path(project["docs_path"]) / "gate-heavy-results"
        if project.get("docs_mode") == "external"
        else Path(project["code_path"]) / "gate-heavy-results"
    )
    measured = f"{gates['measured_seconds']}s" if gates.get("measured_seconds") else "over budget"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        HEAVY_SCRIPT_TEMPLATE.format(
            name=project["name"],
            measured=measured,
            threshold=gates["threshold_seconds"],
            results_dir=str(results_dir),
            code_path=project["code_path"],
            full_cmd=gates["full"].replace('"', '`"'),
        ),
        encoding="utf-8",
    )
    return target


def cmd_profile_gates(project: dict[str, Any], args: argparse.Namespace) -> int:
    code = Path(project["code_path"])
    detected = detect_stack(code)
    if args.fast_cmd:
        detected["fast_cmd"] = args.fast_cmd
    if args.full_cmd:
        detected["full_cmd"] = args.full_cmd
        detected["declared_heavy"] = False
    measured = None
    if args.measure and detected.get("full_cmd") and not detected.get("declared_heavy"):
        print(f"Measuring: {detected['full_cmd']} (stops at {args.threshold_seconds}s)...")
        measured = measure(detected["full_cmd"], code, args.threshold_seconds)
    gates = decide(detected, measured, args.threshold_seconds)

    print(f"Project:   {project['name']} ({code})")
    print(f"Stacks:    {', '.join(gates['stacks'])}")
    print(f"Fast gate: {gates['fast'] or '(none detected)'}")
    print(f"Full gate: {gates['full'] or '(none detected)'}")
    print(f"Mode:      {gates['mode'].upper()} — {gates['reason']}")

    if args.apply:
        if gates["mode"] == "heavy" and not detected.get("declared_heavy"):
            script = write_heavy_script(project, gates)
            if script:
                print(f"Wrote Heavy Gate script: {script}")
            target = heavy_script_path(project)
            if target.exists():
                # Also on re-profile, when the script already exists and was not rewritten.
                gates["heavy_script"] = str(target)
        elif detected.get("declared_heavy"):
            gates["heavy_script"] = "scripts/finalgates.ps1"
        project = {**project, "gates": gates}
        projects.upsert_project(project)
        print(f"Saved gate profile to {projects.registry_path()}")
    return 0
